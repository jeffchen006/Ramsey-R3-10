#!/usr/bin/env python3
"""Export the case table of agent `cases` (pinned copy) to Lean, for one tag.

Writes R310/LP/Data/<Mod>Surv.lean, <Mod>Lpk.lean, <Mod>T9<Scen><b>.lean, <Mod>T9<Scen>.lean
and R310/LP/Cases<Mod>.lean. Untrusted helper: Lean checks everything (kernel `decide`).
Each certificate is converted to Lean rows (M-variables, integer multipliers) and re-checked
here with the same integer arithmetic as `R310.LP.Cert.check`.

Usage: tools/venv/bin/python lean/scripts/export_lean.py PIN_DIR TAG ELB MTF LEAN_DIR [BATCH]
"""
import json
import os
import sys

PIN, TAG, ELB, MTF, LEAN = sys.argv[1], sys.argv[2], int(sys.argv[3]), sys.argv[4] == "1", sys.argv[5]
BATCH = int(sys.argv[6]) if len(sys.argv) > 6 else 100
sys.argv = sys.argv[:4]  # export_certs reads argv at import
sys.path.insert(0, os.path.dirname(__file__))
import export_certs as EC  # noqa: E402  (also imports the pinned degseq as EC.D)
import lean_simple as LS  # noqa: E402

D = EC.D
DEGS = D.DEGS
REG = (0, 0, 0, 0, 0, 40)
SCEN = {k: sorted(v.items()) for k, v in D.SCENARIOS.items()}
MOD = "".join(w.capitalize() for w in TAG.split("_"))
DATA = os.path.join(LEAN, "R310", "LP", "Data")
mtf = "true" if MTF else "false"


def L(xs):
    return "[" + ",".join(map(str, xs)) + "]"


def scenL(U, t):
    Ud = dict(U)
    return tuple(max(D.e9(d), Ud[d] + 1) if d in Ud else D.e9(d) for d in DEGS[:5]) + (t + 1,)


def write(path, text):
    with open(path, "w") as f:
        f.write(text)


HDR = "-- generated by lean/scripts/export_lean.py from {pin} (tag {tag})\n\n"


def main():
    deg = json.load(open(os.path.join(PIN, f"degseq_{TAG}.json")))
    certs = json.load(open(os.path.join(PIN, f"certs_{TAG}.json")))
    assert deg["e_lb"] == ELB
    conv = {}
    for c in certs:
        assert c["mtf"] == MTF
        n, Ll, m, rows = EC.convert(c)
        conv.setdefault((tuple(n), tuple(Ll)), EC.lean_cert(n, Ll, m, rows))
    surv = [tuple(r["n"]) for r in deg["survivors"]]
    assert surv == sorted(surv) and surv[0] == REG
    base = tuple(D.e9(d) for d in DEGS)
    killed = [n for n in D.compositions(40, 6)
              if LS.passSimple(list(n), ELB, MTF) and n not in set(surv)]
    hdr = HDR.format(pin=PIN, tag=TAG)
    # survivors
    write(os.path.join(DATA, f"{MOD}Surv.lean"),
          "import R310.LP.Cert\n\n" + hdr + "namespace R310.LP.Data\n\n"
          "set_option maxHeartbeats 10000000 in\n"
          "set_option maxRecDepth 100000 in\n"
          f"/-- The {len(surv)} surviving degree distributions (n4..n9) of tag `{TAG}`. -/\n"
          f"def surv_{TAG} : List (List ℕ) :=\n  " +
          " ++\n  ".join("[" + ", ".join(L(n) for n in surv[i:i + 200]) + "]"
                         for i in range(0, len(surv), 200)) +
          "\n\nend R310.LP.Data\n")
    # LP-killed
    write(os.path.join(DATA, f"{MOD}Lpk.lean"),
          "import R310.LP.Cases\n\n" + hdr + "namespace R310.LP.Data\n\nopen R310.LP\n\n"
          f"def lpkill_{TAG} : List (List ℕ × Cert) := [\n  " +
          ",\n  ".join(f"({L(n)}, {conv[(n, base)]})" for n in killed) + "]\n\n"
          f"theorem lpkill_{TAG}_ok : lpkOK lpkill_{TAG} {mtf} = true := by decide +kernel\n\n"
          "end R310.LP.Data\n")
    covered = []
    for s, U in SCEN.items():
        rows = []
        miss = 0
        for r in deg["survivors"]:
            n, t = tuple(r["n"]), r["t9_" + s]
            if n == REG:
                continue
            if t is None:
                miss += 1
                continue
            rows.append((n, t, conv[(n, scenL(U, t))]))
        if miss == 0:
            covered.append(s)
        nb = (len(rows) + BATCH - 1) // BATCH
        names = []
        for b in range(nb):
            nm = f"t9_{TAG}_{s}_{b:03d}"
            names.append(nm)
            chunk = rows[b * BATCH:(b + 1) * BATCH]
            write(os.path.join(DATA, f"{MOD}T9{s.capitalize()}{b:03d}.lean"),
                  "import R310.LP.Cases\n\n" + hdr + "namespace R310.LP.Data\n\nopen R310.LP\n\n"
                  f"def {nm} : List (List ℕ × ℕ × Cert) := [\n  " +
                  ",\n  ".join(f"({L(n)}, {t}, {c})" for n, t, c in chunk) + "]\n\n"
                  f"theorem {nm}_ok : t9OK {nm} U_{s} {mtf} = true := by decide +kernel\n\n"
                  "end R310.LP.Data\n")
        write(os.path.join(DATA, f"{MOD}T9{s.capitalize()}.lean"),
              "".join(f"import R310.LP.Data.{MOD}T9{s.capitalize()}{b:03d}\n" for b in range(nb)) +
              "\n" + hdr + "namespace R310.LP.Data\n\nopen R310.LP\n\n"
              f"/-- t9 table of tag `{TAG}`, scenario `{s}` (U = {dict(U)}): (n, t9, certificate). -/\n"
              f"def t9_{TAG}_{s} : List (List ℕ × ℕ × Cert) :=\n  " +
              " ++\n  ".join(names) + "\n\n"
              f"theorem t9_{TAG}_{s}_ok : t9OK t9_{TAG}_{s} U_{s} {mtf} = true := by\n" +
              "".join(f"  have h{b} := {nm}_ok\n" for b, nm in enumerate(names)) +
              "  unfold t9OK at *\n"
              f"  simp only [t9_{TAG}_{s}, List.all_append, " +
              ", ".join(f"h{b}" for b in range(nb)) + ", Bool.and_self]\n\n"
              "end R310.LP.Data\n")
        if miss == 0:
            # the table lists all survivors except the 9-regular one, in order
            assert [r[0] for r in rows] == surv[1:]
    write_cases(surv, covered)
    print(TAG, "survivors", len(surv), "lp-killed", len(killed), "covered", covered)


def write_cases(surv, covered):
    M = 360 - 2 * ELB
    slices = []
    for a in range(3):
        for b in range(3):
            for c in range(max(0, M - 5 * a - 4 * b) // 3 + 1):
                slices.append((a, b, c))
    hyps = ["(G : SimpleGraph (Fin 40)) [DecidableRel G.Adj] (h3 : G.CliqueFree 3)",
            "(hα : G.indepNum ≤ 9)"]
    if MTF:
        hyps.append("(hmtf : IsMTF G)")
    hyps.append("(hR : Ramsey3Le 9 36) (hR8 : Ramsey3Le 8 28) (hT : E39Table)")
    if ELB == 161:
        hyps.append("(hE : EdgeLowerBound 10 40 161)")
    if not MTF:
        hyps.append("(h35 : Regular35)")
    H = "\n    ".join(hyps)
    args = "G h3 hα " + ("hmtf " if MTF else "") + "hR hR8 hT" + (" hE" if ELB == 161 else "") + \
        ("" if MTF else " h35")
    hE = ("(hE.le_card_edgeFinset (by simp) G h3 (by omega))" if ELB == 161
          else "(le_card_edgeFinset G h3 hα hR hT)")
    hm = "(fun _ => hmtf)" if MTF else "(fun h => absurd h (by simp))"
    h35 = ("(fun ⟨u, hu⟩ => absurd hu (by have := hmtf.six_le_degree G hα u; omega))" if MTF
           else "(fun _ => h35)")
    desc = "maximal triangle-free (3,10,40)-graph" if MTF else "(3,10,40)-graph"
    hyp_doc = ("R(3,9) <= 36, R(3,8) <= 28, e(3,9,30..35) table" +
               (", e(3,10,40) >= 161" if ELB == 161 else "") +
               ("" if MTF else ", every (3,9,35)-graph is 8-regular"))
    out = [f"""/-
Case table `{TAG}` of agent `cases` (e(G) >= {ELB}{', MTF' if MTF else ''}), checked by the kernel.
Data: R310/LP/Data/{MOD}*.lean, generated from {PIN}.
Hypotheses of the final theorems: {hyp_doc}.
-/
import R310.LP.Data.{MOD}Surv
import R310.LP.Data.{MOD}Lpk
""" + "".join(f"import R310.LP.Data.{MOD}T9{s.capitalize()}\n" for s in SCEN) + f"""
open Finset

namespace R310.LP.Data

open R310 R310.LP SimpleGraph

/-- Enumeration slice `(n4, n5, n6) = (a, b, c)`. -/
def enumSl_{TAG} (a b c : ℕ) : Bool :=
  (List.range ((360 - 2 * {ELB} - 5 * a - 4 * b - 3 * c) / 2 + 1)).all fun d =>
    (List.range (360 - 2 * {ELB} - 5 * a - 4 * b - 3 * c - 2 * d + 1)).all fun e =>
      !decide (a + b + c + d + e ≤ 40) ||
        !passSimple [a, b, c, d, e, 40 - (a + b + c + d + e)] {ELB} {mtf} ||
        good (surv_{TAG}.filter fun n => n.take 3 == [a, b, c]) lpkill_{TAG}
          [a, b, c, d, e, 40 - (a + b + c + d + e)]
"""]
    for (a, b, c) in slices:
        out.append(f"theorem enumSl_{TAG}_{a}_{b}_{c} : enumSl_{TAG} {a} {b} {c} = true := "
                   "by decide +kernel\n")
    out.append(f"""
theorem enumSl_{TAG}_all (a b c : ℕ) (ha : a < 3) (hb : b < 3)
    (hc : c < (360 - 2 * {ELB} - 5 * a - 4 * b) / 3 + 1) : enumSl_{TAG} a b c = true := by
  interval_cases a <;> interval_cases b <;> simp at hc <;> interval_cases c
{"".join(f"  · exact enumSl_{TAG}_{a}_{b}_{c}" + chr(10) for a, b, c in slices)}
theorem good_filter {{surv : List (List ℕ)}} {{lpk : List (List ℕ × Cert)}} {{p : List ℕ → Bool}}
    {{n : List ℕ}} (h : good (surv.filter p) lpk n = true) : good surv lpk n = true := by
  unfold good at h ⊢
  simp only [Bool.or_eq_true, List.contains_iff_mem, List.mem_filter] at h ⊢
  tauto

theorem enum_{TAG} : enumOK {ELB} {mtf} surv_{TAG} lpkill_{TAG} = true := by
  unfold enumOK enumSlice
  simp only [List.all_eq_true, List.mem_range]
  intro a ha b hb c hc d hd e he
  have h := enumSl_{TAG}_all a b c ha hb hc
  unfold enumSl_{TAG} at h
  simp only [List.all_eq_true, List.mem_range] at h
  have := h d hd e he
  simp only [Bool.or_eq_true] at this ⊢
  rcases this with h1 | h1
  · exact Or.inl h1
  · exact Or.inr (good_filter h1)

/-- Case table: the degree distribution `(n4..n9)` of every {desc} is in `surv_{TAG}`. -/
theorem caseTable_{TAG}
    {H} :
    distOf G ∈ surv_{TAG} :=
  caseTable h3 hα hR hR8 hT enum_{TAG} lpkill_{TAG}_ok {hE} {hm} {h35}
""")
    for s in covered:
        out.append(f"""
theorem cov_{TAG}_{s} : covered surv_{TAG} t9_{TAG}_{s} = true := by
  apply covered_of_eq
  decide +kernel

/-- t9 table, scenario `{s}`: under the gluing hypothesis `Glue U_{s} G`, some 9-vertex `v` of a
{desc} has `e(H_v) ≤ t9of t9_{TAG}_{s} (distOf G)`. -/
theorem t9_{TAG}_{s}_main
    {H}
    (hglue : Glue U_{s} G) :
    ∃ v, G.degree v = 9 ∧ #(delNbhd G v).edgeFinset ≤ t9of t9_{TAG}_{s} (distOf G) :=
  t9_main h3 hα hR hR8 hT t9_{TAG}_{s}_ok cov_{TAG}_{s} (caseTable_{TAG} {args}) {hm} hglue
""")
    out.append("\nend R310.LP.Data\n")
    write(os.path.join(LEAN, "R310", "LP", f"Cases{MOD}.lean"), "".join(out))


if __name__ == "__main__":
    main()
